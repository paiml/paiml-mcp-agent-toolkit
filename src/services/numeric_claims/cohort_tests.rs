/// `run_r1` is the integration seam: an in-memory corpus in, shared-shape
/// findings and the R1 half of the census out.
#[test]
fn run_r1_fills_the_shared_census() {
    let files: Vec<CorpusFile> = readme_corpus(&["70", "70", "70", "70", "70", "70", "75", "75"])
        .into_iter()
        .map(|(p, t)| CorpusFile::new(p, t))
        .collect();
    let out = run_r1(&files, &CohortConfig::default());

    assert_eq!(out.findings.len(), 1);
    assert_eq!(out.findings[0].rule, super::RuleId::R1);
    assert_eq!(out.findings[0].sites.len(), 8);
    assert_eq!(out.census.r1_framed_numerals, 8);
    assert_eq!(out.census.r1_cohorts_min2, 1);
    assert_eq!(out.census.r1_cohorts_at_min_sites, 1);
    assert!(out.warnings.is_empty());

    let lowered = run_r1(
        &files,
        &CohortConfig {
            min_sites: 3,
            ..CohortConfig::default()
        },
    );
    assert_eq!(lowered.warnings.len(), 1, "a lowered floor must warn");
}

/// Findings are ordered and grouped deterministically: the same corpus in a
/// different file order produces byte-identical output. A check whose report
/// churns cannot be diffed in review.
#[test]
fn output_is_deterministic_regardless_of_input_order() {
    let files = readme_corpus(&["75", "70", "70", "75", "70", "70", "70", "70"]);
    let forward = lines_of(&files);
    let mut backward = forward.clone();
    backward.reverse();

    let (a, _) = find_replicated_divergence(&forward, &CohortConfig::default());
    let (b, _) = find_replicated_divergence(&backward, &CohortConfig::default());
    assert_eq!(format!("{a:#?}"), format!("{b:#?}"));
    assert_eq!(a[0].values[0].sites[0].file, "crates/pkg1/README.md");
}

// ------------------------------------------------- guards, ordered --

/// The suppression counters are ORDERED: G1 runs first, so a site it removed
/// never reaches G2. On aprender that makes the shipped census read
/// `G2 multi-slot 0` even though G2 independently kills the same false
/// positives — with G1 off, the same corpus records 2 G2 suppressions. A zero
/// in the G2 column means "G1 got there first", never "G2 is idle", and this
/// test is where that is written down.
#[test]
fn guard_counters_are_ordered_g1_then_g2() {
    // One corpus, both defects: generated files that ALSO co-vary in two slots.
    let files: Vec<(String, String)> = co_varying_corpus(&[
        ("657", "293"),
        ("657", "293"),
        ("657", "293"),
        ("657", "293"),
        ("657", "293"),
        ("657", "293"),
        ("608", "165"),
        ("608", "165"),
    ])
    .into_iter()
    .map(|(p, t)| (p.replace("summary.rs", "generated_summary.rs"), t))
    .collect();

    let (findings, both) = find_replicated_divergence(&lines_of(&files), &CohortConfig::default());
    assert!(findings.is_empty());
    assert_eq!(both.suppressed_generated_name, 8);
    assert_eq!(
        both.suppressed_multi_varying_slot, 0,
        "G1 consumed the sites before G2 could see them"
    );

    let g1_off = cfg_with(Guards {
        generated: false,
        ..Guards::default()
    });
    let (findings, g2_only) = find_replicated_divergence(&lines_of(&files), &g1_off);
    assert!(
        findings.is_empty(),
        "G2 alone still kills it: {findings:#?}"
    );
    assert_eq!(g2_only.suppressed_generated_name, 0);
    assert_eq!(
        g2_only.suppressed_multi_varying_slot, 2,
        "and now the counter shows the work G2 was doing all along"
    );
}

