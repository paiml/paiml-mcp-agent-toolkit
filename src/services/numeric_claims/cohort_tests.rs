/// R-7. Six files are silent, seven fire. `--min-sites 7` is the single knob
/// that decides whether this rule is usable: at `--min-sites 3` the measured
/// precision on the reference corpus is 1 in 10.
#[test]
fn r1_silent_below_min_sites() {
    let six = readme_corpus(&["70", "70", "70", "70", "75", "75"]);
    let (findings, census) = find_replicated_divergence(&lines_of(&six), &CohortConfig::default());
    assert!(
        findings.is_empty(),
        "6 files is below the floor: {findings:#?}"
    );
    assert_eq!(
        census.cohorts_min2, 1,
        "the cohort exists, it just does not fire"
    );
    assert_eq!(census.cohorts_at_min_sites, 0);

    let seven = readme_corpus(&["70", "70", "70", "70", "70", "75", "75"]);
    let (findings, census) =
        find_replicated_divergence(&lines_of(&seven), &CohortConfig::default());
    assert_eq!(findings.len(), 1, "7 files reaches the floor");
    assert_eq!(findings[0].n_files, 7);
    assert_eq!(census.cohorts_at_min_sites, 1);
}

/// Lowering `--min-sites` must warn, with the measured number in it. A check
/// that never fires gets its threshold lowered by the next maintainer; the
/// warning is what stops that from silently costing 90% of the precision.
#[test]
fn min_sites_below_default_warns() {
    assert_eq!(min_sites_warning(DEFAULT_MIN_SITES), None);
    assert_eq!(min_sites_warning(DEFAULT_MIN_SITES + 1), None);

    let w = min_sites_warning(3).expect("--min-sites 3 must warn");
    assert!(w.contains('3'), "the warning names the value used: {w}");
    assert!(
        w.contains("1/10") || w.contains("1 in 10"),
        "the warning carries the measured precision: {w}"
    );
}

/// Turning a guard off must warn too — `--include-generated` is a debugging
/// flag, and both guards were measured to take the rule from 1/3 to 1/1.
#[test]
fn disabled_guards_warn() {
    assert_eq!(guards_warning(&Guards::default()), None);
    let w = guards_warning(&BOTH_GUARDS_OFF).expect("disabled guards must warn");
    assert!(w.to_lowercase().contains("guard"), "{w}");
}

