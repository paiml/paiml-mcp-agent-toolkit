/// R-6. Eight machine-written headers where the precondition count and the
/// contract count move together (165 -> 608, 293 -> 657). Two slots vary, so
/// this is one generator's parameterisation of per-crate data, not one
/// quantity restated eight times. The design's central deduction — at most one
/// value can be right — is unsound here, and its own output contained the
/// counterexample.
#[test]
fn r1_silent_on_multi_varying_slots() {
    let files = co_varying_corpus(&[
        ("657", "293"),
        ("657", "293"),
        ("657", "293"),
        ("657", "293"),
        ("657", "293"),
        ("657", "293"),
        ("608", "165"),
        ("608", "165"),
    ]);
    let (findings, census) =
        find_replicated_divergence(&lines_of(&files), &CohortConfig::default());

    assert!(
        findings.is_empty(),
        "G2 should have suppressed {findings:#?}"
    );
    assert_eq!(
        census.suppressed_multi_varying_slot, 2,
        "both varying slots are suppressed, and both are counted"
    );
}

/// ABLATION for R-6. Same bytes, G2 off: both co-varying slots are reported as
/// independent divergences — the 1/3 precision the guard was built to fix.
#[test]
fn g2_ablated_restores_the_co_varying_false_positives() {
    let files = co_varying_corpus(&[
        ("657", "293"),
        ("657", "293"),
        ("657", "293"),
        ("657", "293"),
        ("657", "293"),
        ("657", "293"),
        ("608", "165"),
        ("608", "165"),
    ]);
    let off = cfg_with(Guards {
        single_varying_slot: false,
        ..Guards::default()
    });
    let (findings, census) = find_replicated_divergence(&lines_of(&files), &off);

    assert_eq!(
        findings.len(),
        2,
        "with G2 off both co-varying slots fire, else R-6 proves nothing: {findings:#?}"
    );
    assert_eq!(census.suppressed_multi_varying_slot, 0);
    let mut slots: Vec<usize> = findings.iter().map(|f| f.slot).collect();
    slots.sort_unstable();
    assert_eq!(slots, vec![0, 3], "slots 1 and 2 never vary, so never fire");
}

