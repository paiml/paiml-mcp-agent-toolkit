/// ABLATION for R-5. Same bytes, G1 off: the finding comes back. Without this
/// pair, `r1_silent_on_generated_files` would pass against a rule that reports
/// nothing at all.
#[test]
fn g1_ablated_restores_the_generated_false_positive() {
    let marker = generated_marker_corpus(&["70", "70", "70", "70", "70", "70", "75", "75"]);
    let named = generated_name_corpus(&["70", "70", "70", "70", "70", "70", "75", "75"]);
    let off = cfg_with(Guards {
        generated: false,
        ..Guards::default()
    });

    for (label, files) in [("marker", marker), ("filename", named)] {
        let (findings, census) = find_replicated_divergence(&lines_of(&files), &off);
        assert_eq!(
            findings.len(),
            1,
            "with G1 off the {label} corpus must fire, else R-5 proves nothing"
        );
        assert_eq!(findings[0].wrong_floor, 2);
        assert_eq!(census.suppressed_generated_marker, 0);
        assert_eq!(census.suppressed_generated_name, 0);
    }
}

