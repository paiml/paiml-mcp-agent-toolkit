//! R-4 .. R-8: the R1 rule and its two guards.
//!
//! Every fixture here is a string literal, because [`super::cohort`] and
//! [`super::frame`] never open a path. That is what makes the ablation tests
//! possible: G1 and G2 are switchable in [`Guards`], so each guard is proved by
//! a *pair* — the guard on, silent; the guard off, firing on the same bytes.
//! A silent-on-X test alone would pass against a stub that reports nothing,
//! which is exactly the failure mode `feedback_tests_encode_bugs` warns about.

use super::cohort::{
    claim_lines, find_replicated_divergence, guards_warning, min_sites_warning, run_r1, to_finding,
    ClaimLine, CohortConfig, Guards, ReplicatedDivergence, DEFAULT_MIN_SITES,
};
use super::CorpusFile;

// ---------------------------------------------------------------- fixtures --

/// The specimen the whole check exists for: aprender's per-crate README line,
/// published to crates.io from 83 files with 7 distinct values.
fn readme_corpus(values: &[&str]) -> Vec<(String, String)> {
    values
        .iter()
        .enumerate()
        .map(|(i, v)| {
            (
                format!("crates/pkg{i}/README.md"),
                format!(
                    "# aprender-pkg\n\nPart of the [Aprender](https://github.com/paiml/aprender) \
                     monorepo — {v} workspace crates.\n"
                ),
            )
        })
        .collect()
}

/// The same claim, in files a machine wrote and stamped DO NOT EDIT.
fn generated_marker_corpus(values: &[&str]) -> Vec<(String, String)> {
    readme_corpus(values)
        .into_iter()
        .map(|(p, t)| {
            (
                p,
                format!("<!-- @generated by xtask — DO NOT EDIT. -->\n{t}"),
            )
        })
        .collect()
}

/// The same claim, in files whose *name* says a machine wrote them.
fn generated_name_corpus(values: &[&str]) -> Vec<(String, String)> {
    values
        .iter()
        .enumerate()
        .map(|(i, v)| {
            (
                format!("crates/pkg{i}/src/generated_contracts.rs"),
                format!("// Part of the Aprender monorepo — {v} workspace crates.\n"),
            )
        })
        .collect()
}

/// The header that made the cohort lane 1/3 before G2: every slot co-varies
/// because a generator writes them all from one YAML file.
fn co_varying_corpus(pairs: &[(&str, &str)]) -> Vec<(String, String)> {
    pairs
        .iter()
        .enumerate()
        .map(|(i, (pre, contracts))| {
            (
                format!("crates/pkg{i}/src/summary.rs"),
                format!(
                    "// Total: {pre} preconditions, 20 postconditions, 0 invariants \
                     from {contracts} contracts\n"
                ),
            )
        })
        .collect()
}

fn lines_of(files: &[(String, String)]) -> Vec<ClaimLine> {
    files
        .iter()
        .flat_map(|(p, t)| claim_lines(p, t).0)
        .collect()
}

fn cfg_with(guards: Guards) -> CohortConfig {
    CohortConfig {
        guards,
        ..CohortConfig::default()
    }
}

const BOTH_GUARDS_OFF: Guards = Guards {
    generated: false,
    single_varying_slot: false,
};

fn only(findings: &[ReplicatedDivergence]) -> &ReplicatedDivergence {
    assert_eq!(
        findings.len(),
        1,
        "expected exactly one finding, got {findings:#?}"
    );
    &findings[0]
}

// --------------------------------------------------------------- R-4 fires --

/// R-4. Eight files, one sentence, 6x`70` and 2x`75`. At most one value can be
/// right, so at least two sites are wrong — and the rule reports that floor,
/// never a wrong-count.
#[test]
fn r1_fires_on_replicated_divergence() {
    let files = readme_corpus(&["70", "70", "70", "70", "70", "70", "75", "75"]);
    let (findings, census) =
        find_replicated_divergence(&lines_of(&files), &CohortConfig::default());

    let f = only(&findings);
    assert_eq!(f.wrong_floor, 2, "6 of 8 agree, so >=2 sites are wrong");
    assert_eq!(f.n_sites, 8);
    assert_eq!(f.n_files, 8);
    assert_eq!(f.slot, 0, "the template has exactly one numeral slot");
    assert!(
        f.template.contains("workspace crates"),
        "template should carry the sentence: {}",
        f.template
    );
    assert!(
        !f.template.contains("70") && !f.template.contains("75"),
        "the numerals are the slot, not part of the template: {}",
        f.template
    );
    assert_eq!(f.values.len(), 2);
    assert_eq!((f.values[0].value.as_str(), f.values[0].count), ("70", 6));
    assert_eq!((f.values[1].value.as_str(), f.values[1].count), ("75", 2));
    assert_eq!(census.cohorts_at_min_sites, 1);
    assert_eq!(census.suppressed_generated_marker, 0);
    assert_eq!(census.suppressed_multi_varying_slot, 0);
}

/// The rule reports a DISAGREEMENT FLOOR and nothing else. Automatic anchor
/// resolution was built and measured — 8 labels on aprender, 0 on pmat, and it
/// missed the one anchor that mattered — so the check must never claim to know
/// which of the values is correct.
#[test]
fn r1_never_claims_to_know_which_value_is_right() {
    let files = readme_corpus(&["70", "70", "70", "70", "70", "70", "75", "75"]);
    let (findings, _) = find_replicated_divergence(&lines_of(&files), &CohortConfig::default());
    let f = only(&findings);

    assert!(!f.anchored, "R1 has no anchor and must say so");
    let shared = to_finding(f);
    assert!(!shared.anchored);
    assert_eq!(shared.wrong_floor, 2);
    assert_eq!(shared.rule, super::RuleId::R1);
    let text = format!("{} {} {}", shared.detail, shared.fix, shared.evidence);
    for forbidden in ["is wrong", "correct value", "should be 7", "fraud"] {
        assert!(
            !text.contains(forbidden),
            "R1 output must not assert a truth it cannot know; found {forbidden:?} in {text:?}"
        );
    }
    assert!(
        shared.fix.contains("declare"),
        "the remediation is to enroll the quantity once: {}",
        shared.fix
    );
}

