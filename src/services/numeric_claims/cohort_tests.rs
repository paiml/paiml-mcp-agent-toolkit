///
/// pmat reports **0** R1 findings at the default floor — the correct answer,
/// and also exactly what a rotted extractor would report. So the same corpus is
/// re-run at `--min-sites 3`, where the measured precision collapses to 1/10
/// and the rule fires. Five findings there and none at seven is proof the
/// silence is a threshold decision rather than a dead scanner, and it is the
/// verified control `feedback_falsification_gates_need_a_verified_control`
/// asks for.
///
/// Measured at pmat HEAD: 5,309 files scanned, 7,295 framed numerals, 180
/// cohorts with two or more files, 1 reaching seven, 0 findings.
#[test]
fn r1_is_silent_on_this_repository_and_the_census_proves_it() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let out =
        super::cohort::scan_repo(root, &CohortConfig::default()).expect("pmat is a work tree");

    assert!(
        out.findings.is_empty(),
        "pmat's R1 baseline is zero findings; this is a real change, not a flake: {:#?}",
        out.findings
    );
    // Vacuity guard: a zero over an empty corpus is not a pass.
    assert!(out.census.files_scanned > 1_000, "census: {:?}", out.census);
    assert!(
        out.census.r1_framed_numerals > 1_000,
        "the framing extractor rotted: {:?}",
        out.census
    );
    assert!(
        out.census.r1_cohorts_min2 > 10,
        "the cohort builder rotted: {:?}",
        out.census
    );
    assert!(out.warnings.is_empty());

    let lowered = super::cohort::scan_repo(
        root,
        &CohortConfig {
            min_sites: 3,
            ..CohortConfig::default()
        },
    )
    .expect("pmat is a work tree");
    assert!(
        !lowered.findings.is_empty(),
        "the rule must be able to fire on this corpus, or the zero above proves nothing"
    );
    assert_eq!(lowered.warnings.len(), 1, "and a lowered floor must warn");
}

/// The modal tie-break is deterministic and unreachable. Two values tied for
/// most-common would need `c/n >= 0.60` and `2c <= n` at once, which has no
/// solution — so a tie is always filtered by the share gate before the
/// tie-break can decide anything a reader sees.
#[test]
fn a_modal_tie_can_never_pass_the_share_gate() {
    let files = readme_corpus(&["70", "70", "70", "70", "75", "75", "75", "75"]);
    let (findings, census) =
        find_replicated_divergence(&lines_of(&files), &CohortConfig::default());
    assert!(
        findings.is_empty(),
        "an even split is two populations, not one claim and its stale copies: {findings:#?}"
    );
    assert_eq!(
        census.cohorts_at_min_sites, 1,
        "the gate saw it and declined"
    );

    // And the same eight sites do fire once one value is genuinely modal.
    let files = readme_corpus(&["70", "70", "70", "70", "70", "75", "75", "75"]);
    let (findings, _) = find_replicated_divergence(&lines_of(&files), &CohortConfig::default());
    assert_eq!(only(&findings).wrong_floor, 3);
}

/// The scanner runs over whatever bytes a repository contains. None of these
/// may crash it, and the multi-byte cases must not slice a character in half:
/// the em dash in the specimen line sits one byte before the numeral it
/// introduces.
#[test]
fn the_scanner_survives_adversarial_lines() {
    let nasty = [
        "",
        "—————",
        "70",
        "1,",
        "1,2",
        "1,23",
        "1,234,",
        "_1",
        "1_",
        "1__2",
        ".5",
        "5.",
        "0.0.0.0",
        "١٢٣ arabic-indic digits",
        "— 70 workspace crates — 75 —",
        "日本語 70 crates 日本語",
        "\u{0}70 crates",
        &"9".repeat(400),
        &format!("{} crates", "1,".repeat(200)),
    ];
    for line in nasty {
        let spans = super::frame::scan_numerals(line);
        for s in &spans {
            assert!(line.is_char_boundary(s.start) && line.is_char_boundary(s.end));
            assert!(s.start < s.end && s.end <= line.len());
        }
        let blanked = super::cohort::blank_numerals(line);
        assert!(
            blanked.len() <= line.len() + spans.len() * 3,
            "blanking must not run away on {line:?}"
        );
        let _ = super::frame::frame_line("a.md", 1, line);
        let _ = claim_lines("a.md", line);
    }
}
