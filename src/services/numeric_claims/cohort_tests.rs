fn innocent_corpus() -> Vec<(String, String)> {
    let mut files = Vec::new();
    for (i, item) in INNOCENTS.iter().enumerate() {
        for k in 0..8 {
            let v = if k < 6 { item.a } else { item.b };
            files.push((
                format!("innocent/i{i:02}/site{k}.{}", item.ext),
                format!("{}\n", item.template.replace("{}", v)),
            ));
        }
    }
    files
}

/// R-8. Twenty-six innocent numeral classes, each replicated eight times with a
/// 6/2 divergence, plus one genuine replicated claim. Exactly one finding, and
/// it is the genuine one. The positive control is what keeps this test from
/// passing for the wrong reason.
#[test]
fn innocent_numbers_are_never_flagged() {
    assert_eq!(INNOCENTS.len(), 26, "the negative control is 26 numerals");

    let mut files = innocent_corpus();
    let (findings, _) = find_replicated_divergence(&lines_of(&files), &CohortConfig::default());
    assert!(
        findings.is_empty(),
        "no innocent numeral may be framed as a claim: {findings:#?}"
    );

    files.extend(readme_corpus(&[
        "70", "70", "70", "70", "70", "70", "75", "75",
    ]));
    let (findings, _) = find_replicated_divergence(&lines_of(&files), &CohortConfig::default());
    let f = only(&findings);
    assert!(
        f.template.contains("workspace crates"),
        "the one finding is the planted claim, not an innocent: {}",
        f.template
    );
}

/// Each innocent class, alone, and named in the failure message — so a
