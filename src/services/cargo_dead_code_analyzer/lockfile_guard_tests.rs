//! `LockfileGuard` is the whole of the read-only promise, so it is tested
//! directly rather than only through an analysis that takes a minute to run.
//!
//! The four states that matter are the cross of (lockfile present / absent)
//! before, and (cargo touched it / did not) after. Each one is driven here by
//! writing the "after" state by hand, which is exactly what cargo does to the
//! byte and needs no compiler.

use super::{LockfileGuard, LockfileRestore};

const ORIGINAL: &[u8] = b"# This file is automatically @generated by Cargo.\n\
                          # It is not intended for manual editing.\n\
                          version = 4\n\n\
                          [[package]]\n\
                          name = \"guarded\"\n\
                          version = \"0.1.0\"\n";

/// The detail of a `Failed` restore, asserting the variant rather than
/// panicking on it: `.pmat-ratchet.toml` pins the count of panic-macro calls
/// and it may only go down, so a test helper does not get to add one.
fn failure_detail(outcome: &LockfileRestore) -> &str {
    if let LockfileRestore::Failed(detail) = outcome {
        return detail;
    }
    assert!(
        matches!(outcome, LockfileRestore::Failed(_)),
        "expected a Failed restore; got {outcome:?}"
    );
    ""
}

/// A crate root the guard will resolve to itself: `[workspace]` in its own
/// manifest makes it the workspace root, so `cargo locate-project --workspace`
/// answers with this directory.
fn crate_root() -> tempfile::TempDir {
    let tmp = tempfile::tempdir().expect("tempdir");
    std::fs::write(
        tmp.path().join("Cargo.toml"),
        "[package]\nname = \"guarded\"\nversion = \"0.1.0\"\nedition = \"2021\"\n[workspace]\n",
    )
    .expect("write manifest");
    std::fs::create_dir_all(tmp.path().join("src")).expect("mkdir src");
    std::fs::write(tmp.path().join("src/lib.rs"), "pub fn entry() {}\n").expect("write lib.rs");
    tmp
}

/// THE DEFECT. cargo appended `[[patch.unused]]` because an ambient `[patch]`
/// was in scope; the bytes must come back.
#[test]
fn a_rewritten_lockfile_is_restored_byte_for_byte() {
    let tmp = crate_root();
    let lockfile = tmp.path().join("Cargo.lock");
    std::fs::write(&lockfile, ORIGINAL).expect("write lockfile");

    let guard = LockfileGuard::acquire(tmp.path());
    // Exactly what cargo 1.95 and 1.98 both appended in the measured failure.
    let rewritten = [
        ORIGINAL,
        b"\n[[patch.unused]]\nname = \"pmat\"\nversion = \"3.41.0\"\n",
    ]
    .concat();
    std::fs::write(&lockfile, &rewritten).expect("simulate cargo's rewrite");

    assert_eq!(guard.restore(), LockfileRestore::Restored);
    assert_eq!(
        std::fs::read(&lockfile).expect("read lockfile"),
        ORIGINAL,
        "a read-only analysis left the project's lockfile rewritten"
    );
}

/// #1076 itself: `cargo check` GENERATES a lockfile where there was none, and
/// whether a tree carries one is the project's decision, not pmat's.
#[test]
fn a_generated_lockfile_is_removed_again() {
    let tmp = crate_root();
    let lockfile = tmp.path().join("Cargo.lock");
    assert!(!lockfile.exists(), "fixture starts with no lockfile");

    let guard = LockfileGuard::acquire(tmp.path());
    std::fs::write(&lockfile, ORIGINAL).expect("simulate cargo generating one");

    assert_eq!(guard.restore(), LockfileRestore::Restored);
    assert!(
        !lockfile.exists(),
        "analyse-only left a source-controlled artifact behind"
    );
}

/// The common case must WRITE NOTHING. Rewriting identical bytes still moves
/// the mtime, and a "is the working copy clean" gate reads more than content.
#[test]
fn an_untouched_lockfile_is_not_rewritten() {
    let tmp = crate_root();
    let lockfile = tmp.path().join("Cargo.lock");
    std::fs::write(&lockfile, ORIGINAL).expect("write lockfile");
    let mtime_before = std::fs::metadata(&lockfile)
        .and_then(|m| m.modified())
        .expect("mtime");

    let guard = LockfileGuard::acquire(tmp.path());
    assert_eq!(guard.restore(), LockfileRestore::Untouched);

    assert_eq!(std::fs::read(&lockfile).expect("read"), ORIGINAL);
    assert_eq!(
        std::fs::metadata(&lockfile)
            .and_then(|m| m.modified())
            .expect("mtime"),
        mtime_before,
        "nothing was written, so nothing may have been touched"
    );
}

/// A crate that never had one and never gets one is also `Untouched` — the
/// guard must not invent a removal to report.
#[test]
fn an_absent_lockfile_that_stays_absent_is_untouched() {
    let tmp = crate_root();
    let guard = LockfileGuard::acquire(tmp.path());
    assert_eq!(guard.restore(), LockfileRestore::Untouched);
    assert!(!tmp.path().join("Cargo.lock").exists());
}

/// The `Drop` belt. A panic between spawning cargo and the explicit `restore`
/// must still leave the tree as it was found.
#[test]
fn dropping_the_guard_restores_as_well() {
    let tmp = crate_root();
    let lockfile = tmp.path().join("Cargo.lock");
    std::fs::write(&lockfile, ORIGINAL).expect("write lockfile");

    {
        let _guard = LockfileGuard::acquire(tmp.path());
        std::fs::write(&lockfile, b"rewritten by cargo\n").expect("simulate rewrite");
        // No explicit restore: leaving this scope is the whole test.
    }

    assert_eq!(
        std::fs::read(&lockfile).expect("read lockfile"),
        ORIGINAL,
        "the Drop belt did not fire, so a panic would leave the tree dirty"
    );
}

/// A restore that cannot happen is REPORTED, never swallowed. `run_cargo_check`
/// turns this into an error, because an analysis that modified the tree and
/// could not undo it has not done what it says on the tin.
///
/// The failure is forced by turning the lockfile PATH into a directory rather
/// than by dropping write permission, because the clean room runs its gates as
/// ROOT and a read-only directory is not read-only to root. The first version
/// of this test used `chmod` and passed here while being vacuous in the one
/// environment that found the bug — measured in the PMAT-1403 clean-room GREEN
/// run, where it and its own root-detector were the only two failures.
/// `write()` and `remove_file()` on a directory fail for uid 0 too.
#[test]
fn a_restore_that_cannot_write_is_reported_as_failed() {
    let tmp = crate_root();
    let lockfile = tmp.path().join("Cargo.lock");
    std::fs::write(&lockfile, ORIGINAL).expect("write lockfile");

    let guard = LockfileGuard::acquire(tmp.path());
    std::fs::remove_file(&lockfile).expect("remove");
    std::fs::create_dir(&lockfile).expect("put a directory where the lockfile was");

    let outcome = guard.restore();
    let detail = failure_detail(&outcome);
    assert!(
        detail.contains(crate::models::dead_code::COMPILER_SCAN_REASON_LOCKFILE_RESTORE_FAILED),
        "the failure must carry a stable token a consumer can branch on, not prose: {detail}"
    );
    assert!(
        detail.contains("Cargo.lock"),
        "the failure must NAME the file it could not put back: {detail}"
    );
}

/// The same for the branch that REMOVES: a lockfile-less crate whose path
/// cannot be cleared must say so rather than report success.
///
/// This branch also pins that presence is asked with `exists()` and not with
/// `read().ok()`: a path that exists but cannot be READ used to fall into the
/// `Absent`/absent arm and report `Untouched` over something still sitting in
/// the tree.
#[test]
fn a_removal_that_cannot_happen_is_reported_as_failed() {
    let tmp = crate_root();
    let lockfile = tmp.path().join("Cargo.lock");
    assert!(!lockfile.exists(), "fixture starts with no lockfile");

    let guard = LockfileGuard::acquire(tmp.path());
    std::fs::create_dir(&lockfile).expect("put an unremovable thing where cargo would write");
    std::fs::write(lockfile.join("occupant"), b"x").expect("make it non-empty");

    let outcome = guard.restore();
    let detail = failure_detail(&outcome);
    assert!(
        detail.contains(crate::models::dead_code::COMPILER_SCAN_REASON_LOCKFILE_RESTORE_FAILED)
            && detail.contains("Cargo.lock"),
        "the failure must carry the stable token and name the path: {detail}"
    );
}

/// A workspace MEMBER's analysis must guard the workspace root's lockfile, not
/// a `Cargo.lock` beside the member that cargo would never write. Guarding the
/// wrong path is the bug that looks exactly like the fix.
#[test]
fn a_workspace_member_guards_the_workspace_root_lockfile() {
    let tmp = tempfile::tempdir().expect("tempdir");
    std::fs::write(
        tmp.path().join("Cargo.toml"),
        "[workspace]\nmembers = [\"member\"]\nresolver = \"2\"\n",
    )
    .expect("write workspace manifest");
    let member = tmp.path().join("member");
    std::fs::create_dir_all(member.join("src")).expect("mkdir member");
    std::fs::write(
        member.join("Cargo.toml"),
        "[package]\nname = \"member\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    )
    .expect("write member manifest");
    std::fs::write(member.join("src/lib.rs"), "pub fn entry() {}\n").expect("write lib.rs");

    let guard = LockfileGuard::acquire(&member);
    assert_eq!(
        guard.path(),
        tmp.path().join("Cargo.lock"),
        "cargo keeps one lockfile per WORKSPACE; guarding the member directory \
         would protect a file cargo never writes and leave the real one exposed"
    );
}

/// `CargoCheckOutcome` carries no `Debug`, so `expect_err` cannot name it. The
/// assertion is the point either way: an `Ok` here IS the defect.
fn unreachable_ok() -> anyhow::Error {
    assert!(
        false,
        "a failed restore returned Ok: the failure was swallowed"
    );
    anyhow::anyhow!("unreachable")
}

/// A lockfile that EXISTS but cannot be read must never be deleted.
///
/// Found by quorum review (lane 1, PMAT-1403). `acquire` classified on
/// `fs::read` alone, so an unreadable lockfile was recorded `Absent`; at
/// restore the path existed, the `(Absent, true, _)` arm matched, and the guard
/// REMOVED the project's own file. A mechanism whose entire purpose is to leave
/// the tree alone would have been the thing that destroyed it.
///
/// The unreadable state is forced with a directory rather than `chmod`: the
/// clean room runs its gates as root, where a mode-0 file is still readable.
#[test]
fn a_lockfile_that_exists_but_cannot_be_read_is_never_deleted() {
    let tmp = crate_root();
    let lockfile = tmp.path().join("Cargo.lock");
    std::fs::create_dir(&lockfile).expect("an unreadable thing at the lockfile path");
    std::fs::write(lockfile.join("occupant"), b"x").expect("make it non-empty");

    let guard = LockfileGuard::acquire(tmp.path());
    assert_eq!(
        guard.restore(),
        LockfileRestore::Untouched,
        "there were never any bytes to put back, so the only safe move is none"
    );
    assert!(
        lockfile.exists(),
        "the guard deleted a file it could not read: it is not the analysis's to remove"
    );
}

/// ...and if something else removes it, that IS reported: the analysis ran over
/// a file it could not snapshot and cannot restore.
#[test]
fn an_unreadable_lockfile_that_disappears_is_reported_as_failed() {
    let tmp = crate_root();
    let lockfile = tmp.path().join("Cargo.lock");
    std::fs::create_dir(&lockfile).expect("an unreadable thing at the lockfile path");

    let guard = LockfileGuard::acquire(tmp.path());
    std::fs::remove_dir(&lockfile).expect("simulate cargo clearing the path");

    let outcome = guard.restore();
    let detail = failure_detail(&outcome);
    assert!(
        detail.contains(crate::models::dead_code::COMPILER_SCAN_REASON_LOCKFILE_RESTORE_FAILED)
            && detail.contains("Cargo.lock"),
        "a lockfile that vanished and cannot be rebuilt must carry the token and the path: \
         {detail}"
    );
}

/// A failed restore must reach the caller even when cargo ALSO failed.
///
/// Found by quorum review (lane 1, PMAT-1403). `run_cargo_check` did
/// `let outcome = outcome?;` before looking at the restore, so a cargo failure
/// short-circuited and the restore failure was dropped: the user learned why
/// the analysis stopped and not that it had left their repository modified.
#[test]
fn a_failed_restore_outranks_a_failed_cargo_run_and_is_never_swallowed() {
    use super::cargo_outcome_or_restore_failure;

    let failed = || LockfileRestore::Failed("lockfile-restore-failed: /x/Cargo.lock".into());
    let token = crate::models::dead_code::COMPILER_SCAN_REASON_LOCKFILE_RESTORE_FAILED;

    // cargo failed AND the restore failed: BOTH facts survive.
    let err = match cargo_outcome_or_restore_failure(
        Err(anyhow::anyhow!("Cargo check failed: boom")),
        failed(),
    ) {
        Err(e) => e,
        Ok(_) => unreachable_ok(),
    };
    let text = format!("{err}");
    assert!(
        text.contains(token),
        "the restore failure was swallowed by the cargo error: {text}"
    );
    assert!(
        text.contains("boom"),
        "the cargo error must be carried along, not traded away: {text}"
    );

    // cargo succeeded, the restore failed: still an error.
    let err = match cargo_outcome_or_restore_failure(
        Ok(super::CargoCheckOutcome::suppressed_by_env()),
        failed(),
    ) {
        Err(e) => e,
        Ok(_) => unreachable_ok(),
    };
    assert!(format!("{err}").contains(token));

    // Nothing wrong: the cargo outcome passes through untouched.
    assert!(
        cargo_outcome_or_restore_failure(
            Ok(super::CargoCheckOutcome::suppressed_by_env()),
            LockfileRestore::Untouched
        )
        .is_ok(),
        "a clean restore must not turn a good run into an error"
    );
    assert!(cargo_outcome_or_restore_failure(
        Err(anyhow::anyhow!("Cargo check failed: boom")),
        LockfileRestore::Restored
    )
    .is_err_and(|e| format!("{e}").contains("boom") && !format!("{e}").contains(token)));
}
