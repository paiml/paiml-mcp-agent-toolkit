// Agent contract-first enforcement checks (CB-1400 through CB-1410)
// Included from check.rs — do NOT add `use` imports or `#!` attributes here.
//
// Spec: docs/specifications/components/agent-integration.md (Component 10)
//
// Enforces provable-contract-first design for all agents/sub-agents.
// No agent may generate code without a prior contract (YAML or contract.json).

/// Required patterns in agent context files (CLAUDE.md, GEMINI.md, AGENTS.md)
/// that indicate contract-first methodology is documented.
const AGENT_CONTRACT_PATTERNS: &[&str] = &[
    "contract-first",
    "provable-contract",
    "NEVER write code before",
    "NEVER.*code.*before.*contract",
    "CB-1400",
    "verification_level",
    "pmat comply",
];

/// Known AI agent co-author patterns in git commits
const AI_COAUTHOR_PATTERNS: &[&str] = &[
    "Co-Authored-By: Claude",
    "Co-Authored-By: Copilot",
    "Co-Authored-By: GPT",
    "Co-Authored-By: Gemini",
    "Co-Authored-By: Cursor",
    "Co-Authored-By: Cody",
    "Co-Authored-By: Devin",
    "Co-Authored-By: Codex",
    "generated by ai",
    "ai-generated",
];

/// CB-1400: Agent Contract Existence
///
/// Checks that agent context files (CLAUDE.md, GEMINI.md, AGENTS.md) reference
/// contract-first methodology. If agent context files exist but lack contract-first
/// patterns, the project is not enforcing contract-first for agents.
pub(crate) fn check_agent_contract_existence(project_path: &Path) -> ComplianceCheck {
    let agent_files = [
        "CLAUDE.md",
        "GEMINI.md",
        "AGENTS.md",
        "AGENT.md",
        ".claude/CLAUDE.md",
    ];

    let mut found_agent_files = Vec::new();
    let mut files_with_contract_ref = Vec::new();
    let mut files_missing_contract_ref = Vec::new();

    for agent_file in &agent_files {
        let path = project_path.join(agent_file);
        if path.exists() {
            found_agent_files.push(*agent_file);
            if let Ok(content) = fs::read_to_string(&path) {
                let content_lower = content.to_lowercase();
                let has_contract_ref = AGENT_CONTRACT_PATTERNS
                    .iter()
                    .any(|p| content_lower.contains(&p.to_lowercase()));
                if has_contract_ref {
                    files_with_contract_ref.push(*agent_file);
                } else {
                    files_missing_contract_ref.push(*agent_file);
                }
            }
        }
    }

    if found_agent_files.is_empty() {
        return ComplianceCheck {
            name: "CB-1400: Agent Contract Existence".into(),
            status: CheckStatus::Skip,
            message: "No agent context files found (CLAUDE.md, AGENTS.md, etc.)".into(),
            severity: Severity::Info,
        };
    }

    if files_missing_contract_ref.is_empty() {
        ComplianceCheck {
            name: "CB-1400: Agent Contract Existence".into(),
            status: CheckStatus::Pass,
            message: format!(
                "{}/{} agent context file(s) reference contract-first design",
                files_with_contract_ref.len(),
                found_agent_files.len()
            ),
            severity: Severity::Info,
        }
    } else {
        ComplianceCheck {
            name: "CB-1400: Agent Contract Existence".into(),
            status: CheckStatus::Fail,
            message: format!(
                "{} agent context file(s) lack contract-first reference: {}",
                files_missing_contract_ref.len(),
                files_missing_contract_ref.join(", ")
            ),
            severity: Severity::Error,
        }
    }
}

/// CB-1401: Agent Contract Falsifiability
///
/// Checks that work contracts in .pmat-work/ have falsifiable claims with
/// actual evidence commands (not just descriptions). Contracts with empty
/// evidence fields or placeholder-only claims are flagged.
pub(crate) fn check_agent_contract_falsifiability(project_path: &Path) -> ComplianceCheck {
    let work_dir = project_path.join(".pmat-work");
    if !work_dir.exists() {
        return ComplianceCheck {
            name: "CB-1401: Agent Contract Falsifiability".into(),
            status: CheckStatus::Skip,
            message: "No .pmat-work/ directory found".into(),
            severity: Severity::Info,
        };
    }

    let mut total_contracts = 0usize;
    let mut contracts_with_evidence = 0usize;
    let mut contracts_without_evidence = Vec::new();

    if let Ok(entries) = fs::read_dir(&work_dir) {
        for entry in entries.flatten() {
            let contract_path = entry.path().join("contract.json");
            if !contract_path.exists() {
                continue;
            }
            total_contracts += 1;

            if let Ok(content) = fs::read_to_string(&contract_path) {
                // Check for evidence fields in the contract
                let has_evidence = content.contains("\"evidence\":")
                    && !content.contains("\"evidence\": \"\"")
                    && !content.contains("\"evidence\":\"\"");

                // Check for require/ensure/invariant clauses (DbC v5.0)
                let has_dbc = content.contains("\"require\":")
                    || content.contains("\"ensure\":")
                    || content.contains("\"invariant\":");

                // Check for falsifiable claims
                let has_claims = content.contains("\"claims\":");

                if (has_evidence && has_dbc) || has_claims {
                    contracts_with_evidence += 1;
                } else {
                    let id = entry
                        .file_name()
                        .to_string_lossy()
                        .to_string();
                    if contracts_without_evidence.len() < 5 {
                        contracts_without_evidence.push(id);
                    }
                }
            }
        }
    }

    if total_contracts == 0 {
        return ComplianceCheck {
            name: "CB-1401: Agent Contract Falsifiability".into(),
            status: CheckStatus::Skip,
            message: "No work contracts found in .pmat-work/".into(),
            severity: Severity::Info,
        };
    }

    if contracts_without_evidence.is_empty() {
        ComplianceCheck {
            name: "CB-1401: Agent Contract Falsifiability".into(),
            status: CheckStatus::Pass,
            message: format!(
                "{}/{} work contract(s) have falsifiable claims with evidence",
                contracts_with_evidence, total_contracts
            ),
            severity: Severity::Info,
        }
    } else {
        ComplianceCheck {
            name: "CB-1401: Agent Contract Falsifiability".into(),
            status: CheckStatus::Fail,
            message: format!(
                "{} contract(s) lack falsifiable evidence: {}",
                contracts_without_evidence.len(),
                contracts_without_evidence.join(", ")
            ),
            severity: Severity::Error,
        }
    }
}

/// CB-1402: Agent Verification Level Floor
///
/// Checks that work contracts specify a verification level >= L1 for
/// autonomous agents. L0 (paper-only/human review) is not acceptable
/// for autonomous agent work.
pub(crate) fn check_agent_verification_level(project_path: &Path) -> ComplianceCheck {
    let work_dir = project_path.join(".pmat-work");
    if !work_dir.exists() {
        return ComplianceCheck {
            name: "CB-1402: Agent Verification Level".into(),
            status: CheckStatus::Skip,
            message: "No .pmat-work/ directory found".into(),
            severity: Severity::Info,
        };
    }

    let mut total_contracts = 0usize;
    let mut l0_contracts = Vec::new();
    let mut no_level_contracts = Vec::new();

    if let Ok(entries) = fs::read_dir(&work_dir) {
        for entry in entries.flatten() {
            let contract_path = entry.path().join("contract.json");
            if !contract_path.exists() {
                continue;
            }
            total_contracts += 1;

            if let Ok(content) = fs::read_to_string(&contract_path) {
                let id = entry.file_name().to_string_lossy().to_string();

                if content.contains("\"verification_level\"") {
                    // Check for L0 — paper-only, unacceptable for autonomous agents
                    if content.contains("\"L0\"") || content.contains("\"l0\"") {
                        if l0_contracts.len() < 5 {
                            l0_contracts.push(id);
                        }
                    }
                    // L1+ is acceptable
                } else {
                    // No verification level specified — pre-v5.0 contract
                    if no_level_contracts.len() < 5 {
                        no_level_contracts.push(id);
                    }
                }
            }
        }
    }

    if total_contracts == 0 {
        return ComplianceCheck {
            name: "CB-1402: Agent Verification Level".into(),
            status: CheckStatus::Skip,
            message: "No work contracts found".into(),
            severity: Severity::Info,
        };
    }

    if !l0_contracts.is_empty() {
        ComplianceCheck {
            name: "CB-1402: Agent Verification Level".into(),
            status: CheckStatus::Fail,
            message: format!(
                "{} contract(s) at L0 (paper-only) — autonomous agents require >= L1: {}",
                l0_contracts.len(),
                l0_contracts.join(", ")
            ),
            severity: Severity::Error,
        }
    } else if !no_level_contracts.is_empty() {
        ComplianceCheck {
            name: "CB-1402: Agent Verification Level".into(),
            status: CheckStatus::Warn,
            message: format!(
                "{} contract(s) missing verification_level field: {}",
                no_level_contracts.len(),
                no_level_contracts.join(", ")
            ),
            severity: Severity::Warning,
        }
    } else {
        ComplianceCheck {
            name: "CB-1402: Agent Verification Level".into(),
            status: CheckStatus::Pass,
            message: format!(
                "{} work contract(s) at verification level >= L1",
                total_contracts
            ),
            severity: Severity::Info,
        }
    }
}

/// CB-1403: Assume-Guarantee Chain Validation
///
/// For multi-agent workflows, validates that work contract ensure clauses
/// from one phase align with require clauses of the next phase.
/// Currently checks that contracts with "parent" or "depends_on" references
/// have matching clause structure.
pub(crate) fn check_assume_guarantee_chain(project_path: &Path) -> ComplianceCheck {
    let work_dir = project_path.join(".pmat-work");
    if !work_dir.exists() {
        return ComplianceCheck {
            name: "CB-1403: Assume-Guarantee Chain".into(),
            status: CheckStatus::Skip,
            message: "No .pmat-work/ directory found".into(),
            severity: Severity::Info,
        };
    }

    // Collect contracts that reference other work items (chain indicators)
    let mut chained_contracts = 0usize;
    let mut total_contracts = 0usize;

    if let Ok(entries) = fs::read_dir(&work_dir) {
        for entry in entries.flatten() {
            let contract_path = entry.path().join("contract.json");
            if !contract_path.exists() {
                continue;
            }
            total_contracts += 1;

            if let Ok(content) = fs::read_to_string(&contract_path) {
                // Look for chain indicators: iteration > 1, parent references, or
                // require clauses that reference other ticket IDs
                let has_chain_ref = content.contains("\"iteration\":")
                    && !content.contains("\"iteration\": 1")
                    && !content.contains("\"iteration\":1");
                let has_parent = content.contains("\"parent_agent\"")
                    || content.contains("\"depends_on\"");
                let has_refs_pattern = content.contains("Refs PMAT-")
                    || content.contains("refs PMAT-");

                if has_chain_ref || has_parent || has_refs_pattern {
                    chained_contracts += 1;
                }
            }
        }
    }

    if total_contracts == 0 {
        return ComplianceCheck {
            name: "CB-1403: Assume-Guarantee Chain".into(),
            status: CheckStatus::Skip,
            message: "No work contracts found".into(),
            severity: Severity::Info,
        };
    }

    // Info-level: report chain status. Future: validate clause alignment.
    ComplianceCheck {
        name: "CB-1403: Assume-Guarantee Chain".into(),
        status: CheckStatus::Pass,
        message: format!(
            "{}/{} contract(s) participate in assume-guarantee chains",
            chained_contracts, total_contracts
        ),
        severity: Severity::Info,
    }
}

/// CB-1408: Agent Evidence Executability
///
/// Checks that work contracts have valid evidence mechanisms — either
/// "evidence": "command" strings (DbC v5.0 spec format) or
/// "falsification_method": "MethodName" (Popperian claims format).
/// Contracts with placeholder-only evidence are flagged.
pub(crate) fn check_agent_evidence_executable(project_path: &Path) -> ComplianceCheck {
    let work_dir = project_path.join(".pmat-work");
    if !work_dir.exists() {
        return ComplianceCheck {
            name: "CB-1408: Agent Evidence Executable".into(),
            status: CheckStatus::Skip,
            message: "No .pmat-work/ directory found".into(),
            severity: Severity::Info,
        };
    }

    let mut total_contracts = 0usize;
    let mut contracts_with_evidence = 0usize;
    let mut contracts_without_evidence = Vec::new();

    // Known valid falsification methods (Popperian claims format)
    let valid_methods = [
        "ManifestIntegrity", "MetaFalsification", "CoverageGaming",
        "DifferentialCoverage", "AbsoluteCoverage", "TdgRegression",
        "ComplexityRegression", "FileSizeRegression", "SpecQuality",
        "GitHubSync", "SupplyChainIntegrity", "SatdRegression",
        "DeadCodeRegression", "UnwrapRegression",
    ];

    // Known placeholder patterns
    let placeholder_patterns = ["TODO", "FIXME", "placeholder", "TBD"];

    if let Ok(entries) = fs::read_dir(&work_dir) {
        for entry in entries.flatten() {
            let contract_path = entry.path().join("contract.json");
            if !contract_path.exists() {
                continue;
            }
            total_contracts += 1;

            if let Ok(content) = fs::read_to_string(&contract_path) {
                let id = entry.file_name().to_string_lossy().to_string();

                // Check for Popperian falsification methods
                let has_methods = valid_methods
                    .iter()
                    .any(|m| content.contains(m));

                // Check for evidence command strings
                let has_evidence_cmds = content.contains("\"evidence\":")
                    && !content.contains("\"evidence\": \"\"");

                // Check for placeholder-dominated evidence
                let is_placeholder = has_evidence_cmds
                    && !has_methods
                    && content
                        .lines()
                        .filter(|l| l.contains("\"evidence\""))
                        .all(|l| placeholder_patterns.iter().any(|pp| l.contains(pp)));

                if (has_methods || has_evidence_cmds) && !is_placeholder {
                    contracts_with_evidence += 1;
                } else if contracts_without_evidence.len() < 5 {
                    contracts_without_evidence.push(id);
                }
            }
        }
    }

    if total_contracts == 0 {
        return ComplianceCheck {
            name: "CB-1408: Agent Evidence Executable".into(),
            status: CheckStatus::Skip,
            message: "No work contracts found".into(),
            severity: Severity::Info,
        };
    }

    if contracts_without_evidence.is_empty() {
        ComplianceCheck {
            name: "CB-1408: Agent Evidence Executable".into(),
            status: CheckStatus::Pass,
            message: format!(
                "{}/{} contract(s) have valid evidence mechanisms (falsification methods or commands)",
                contracts_with_evidence, total_contracts
            ),
            severity: Severity::Info,
        }
    } else {
        ComplianceCheck {
            name: "CB-1408: Agent Evidence Executable".into(),
            status: CheckStatus::Fail,
            message: format!(
                "{} contract(s) lack valid evidence: {}",
                contracts_without_evidence.len(),
                contracts_without_evidence.join(", ")
            ),
            severity: Severity::Error,
        }
    }
}

/// CB-1409: No L0 Autonomous Code
///
/// Checks recent git commits for AI co-author markers. If found, verifies
/// that a corresponding work contract exists in .pmat-work/. AI-authored
/// commits without contracts indicate L0 (paper-only) autonomous code.
pub(crate) fn check_no_l0_autonomous_code(project_path: &Path) -> ComplianceCheck {
    // Get recent commits (last 20)
    let output = match std::process::Command::new("git")
        .args(["log", "--format=%H %s%n%b", "-20"])
        .current_dir(project_path)
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::null())
        .output()
    {
        Ok(o) => o,
        Err(_) => {
            return ComplianceCheck {
                name: "CB-1409: No L0 Autonomous Code".into(),
                status: CheckStatus::Skip,
                message: "Unable to read git log".into(),
                severity: Severity::Info,
            };
        }
    };

    let log_output = String::from_utf8_lossy(&output.stdout);
    if log_output.is_empty() {
        return ComplianceCheck {
            name: "CB-1409: No L0 Autonomous Code".into(),
            status: CheckStatus::Skip,
            message: "No git history found".into(),
            severity: Severity::Info,
        };
    }

    let mut ai_commits = 0usize;
    let mut ai_commits_with_contract = 0usize;
    let mut ai_commits_without_contract = Vec::new();

    // Collect existing work item IDs
    let work_dir = project_path.join(".pmat-work");
    let mut known_work_ids: Vec<String> = Vec::new();
    if work_dir.exists() {
        if let Ok(entries) = fs::read_dir(&work_dir) {
            for entry in entries.flatten() {
                if entry.path().is_dir() {
                    known_work_ids.push(entry.file_name().to_string_lossy().to_string());
                }
            }
        }
    }

    // Parse git log output — format is: <hash> <subject>\n<body>\n
    let mut current_subject = String::new();
    let mut current_body = String::new();
    let mut in_body = false;

    for line in log_output.lines() {
        // New commit starts with a 40-char hex hash
        if line.len() > 41 && line.chars().take(40).all(|c| c.is_ascii_hexdigit()) {
            // Process previous commit if it was AI-authored
            if !current_subject.is_empty() {
                process_commit_for_ai_check(
                    &current_subject,
                    &current_body,
                    &known_work_ids,
                    &mut ai_commits,
                    &mut ai_commits_with_contract,
                    &mut ai_commits_without_contract,
                );
            }
            current_subject = line[41..].to_string();
            current_body.clear();
            in_body = false;
        } else {
            if !in_body {
                in_body = true;
            }
            current_body.push_str(line);
            current_body.push('\n');
        }
    }
    // Process the last commit
    if !current_subject.is_empty() {
        process_commit_for_ai_check(
            &current_subject,
            &current_body,
            &known_work_ids,
            &mut ai_commits,
            &mut ai_commits_with_contract,
            &mut ai_commits_without_contract,
        );
    }

    if ai_commits == 0 {
        return ComplianceCheck {
            name: "CB-1409: No L0 Autonomous Code".into(),
            status: CheckStatus::Pass,
            message: "No AI-authored commits in recent history (last 20 commits)".into(),
            severity: Severity::Info,
        };
    }

    if ai_commits_without_contract.is_empty() {
        ComplianceCheck {
            name: "CB-1409: No L0 Autonomous Code".into(),
            status: CheckStatus::Pass,
            message: format!(
                "{}/{} AI-authored commit(s) have corresponding work contracts",
                ai_commits_with_contract, ai_commits
            ),
            severity: Severity::Info,
        }
    } else {
        let examples: Vec<&str> = ai_commits_without_contract
            .iter()
            .take(3)
            .map(|s| s.as_str())
            .collect();
        ComplianceCheck {
            name: "CB-1409: No L0 Autonomous Code".into(),
            status: CheckStatus::Warn,
            message: format!(
                "{}/{} AI-authored commit(s) lack work contracts: {}",
                ai_commits_without_contract.len(),
                ai_commits,
                examples.join("; ")
            ),
            severity: Severity::Warning,
        }
    }
}

/// Helper: check if a commit is AI-authored and has a work contract reference
fn process_commit_for_ai_check(
    subject: &str,
    body: &str,
    known_work_ids: &[String],
    ai_commits: &mut usize,
    ai_commits_with_contract: &mut usize,
    ai_commits_without_contract: &mut Vec<String>,
) {
    let full_text = format!("{}\n{}", subject, body);
    let is_ai = AI_COAUTHOR_PATTERNS
        .iter()
        .any(|p| full_text.to_lowercase().contains(&p.to_lowercase()));

    if !is_ai {
        return;
    }

    *ai_commits += 1;

    // Check if commit references a known work item
    let has_contract_ref = known_work_ids
        .iter()
        .any(|id| full_text.contains(id));

    // Also check for Refs PMAT-xxx pattern
    let has_refs = full_text.contains("Refs PMAT-")
        || full_text.contains("refs PMAT-")
        || full_text.contains("Contract:");

    if has_contract_ref || has_refs {
        *ai_commits_with_contract += 1;
    } else {
        let truncated = if subject.len() > 60 {
            format!("{}...", &subject[..57])
        } else {
            subject.to_string()
        };
        if ai_commits_without_contract.len() < 5 {
            ai_commits_without_contract.push(truncated);
        }
    }
}

/// CB-1410: Sub-Agent Contract Composition
///
/// Validates that iterative work contracts (iteration > 1) properly
/// reference their predecessor's postconditions. Checks that the
/// contract chain is continuous.
pub(crate) fn check_subagent_contract_composition(project_path: &Path) -> ComplianceCheck {
    let work_dir = project_path.join(".pmat-work");
    if !work_dir.exists() {
        return ComplianceCheck {
            name: "CB-1410: Sub-Agent Composition".into(),
            status: CheckStatus::Skip,
            message: "No .pmat-work/ directory found".into(),
            severity: Severity::Info,
        };
    }

    let mut total_contracts = 0usize;
    let mut iterated_contracts = 0usize;

    // Check for contracts with iteration markers or receipt chains
    if let Ok(entries) = fs::read_dir(&work_dir) {
        for entry in entries.flatten() {
            let contract_path = entry.path().join("contract.json");
            if !contract_path.exists() {
                continue;
            }
            total_contracts += 1;

            // Check for falsification receipts (indicates contract was evaluated)
            let receipt_dir = entry.path().join("falsification");
            if receipt_dir.exists() {
                if let Ok(receipts) = fs::read_dir(&receipt_dir) {
                    let receipt_count = receipts.filter_map(|r| r.ok()).count();
                    if receipt_count > 1 {
                        iterated_contracts += 1;
                    }
                }
            }
        }
    }

    if total_contracts == 0 {
        return ComplianceCheck {
            name: "CB-1410: Sub-Agent Composition".into(),
            status: CheckStatus::Skip,
            message: "No work contracts found".into(),
            severity: Severity::Info,
        };
    }

    ComplianceCheck {
        name: "CB-1410: Sub-Agent Composition".into(),
        status: CheckStatus::Pass,
        message: format!(
            "{}/{} contract(s) have multi-iteration falsification chains",
            iterated_contracts, total_contracts
        ),
        severity: Severity::Info,
    }
}

